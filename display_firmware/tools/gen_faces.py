#!/usr/bin/env python3
"""Writes xindi/screen/faces.py from tools/faces.json (the names of the tiles of every look of a widget) and the
position of the pictures in project.json.

    python3 tools/gen_faces.py            writes the file
    python3 tools/gen_faces.py --check    exits 1 when the file is not what the project says (the ids moved)

``g.port.face(widget, state)`` of the host sends the two tiles of a state (released, pressed); the ids are the
positions of the pictures, so run this after pictures were added in front of them or removed. tile_pictures.py made
faces.json from the looks the stock host set (tile_spec.py); add a look by hand: ``"widget": {"state": ["tile", "tile_press"]}``
(the pressed tile may be null).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FACES_PY = os.path.join(os.path.dirname(ROOT), "xindi", "screen", "faces.py")


def render():
    with open(os.path.join(ROOT, "project.json"), encoding="utf-8") as f:
        keys = [p["key"] for p in json.load(f)["pictures"]]
    with open(os.path.join(ROOT, "tools", "faces.json"), encoding="utf-8") as f:
        faces = json.load(f)
    lines = ['"""Looks of the widgets that the host switches while the screen runs: ``g.port.face(widget, state)``.',
             "Picture ids of the tiles (their position in display_firmware/project.json). Generated by",
             'display_firmware/tools/gen_faces.py from tools/faces.json; do not edit."""', "", "FACES = {"]
    for widget, states in sorted(faces.items()):
        lines.append('    "%s": {' % widget)
        for state, (released, pressed) in sorted(states.items()):
            ids = ['"%d"' % keys.index(released), '"%d"' % keys.index(pressed) if pressed else "None"]
            lines.append('        "%s": (%s),' % (state, ", ".join(ids)))
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        with open(FACES_PY, encoding="utf-8") as f:
            if f.read() != text:
                print("xindi/screen/faces.py is out of date: run tools/gen_faces.py")
                return 1
        print("faces.py ok")
        return 0
    with open(FACES_PY, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
