"""Host text for the new display: fit names using the advances of its single wide font.

font_t16.widths is generated by display_firmware/tools/make_fonts.py, not browser/TTF metrics.
The full file name stays in state; only the displayed copy is shortened. Non-BMP/missing glyphs
are replaced by '?' and controls by spaces, so neither a name nor an SSID can inject screen code.
"""
import unicodedata
from pathlib import Path

ERR_MSG_WIDTH, ERR_MSG_LINES = 190, 6          # klipper_error: err_msg is 190 x 132 px, the wide font has a 20 px line
POPUP_MSG_WIDTH, POPUP_MSG_LINES = 216, 8      # error / gcode_error: msg is 216 x 170 px

WIDTHS = (Path(__file__).with_name("font_t16.widths")).read_bytes()
if len(WIDTHS) != 65536:
    raise ValueError("invalid screen font width table")


def clean(value):
    value = unicodedata.normalize("NFC", str(value)).replace('"', "'").replace("\\", "/")
    return "".join(" " if unicodedata.category(ch).startswith("C") else
                   ch if ord(ch) < len(WIDTHS) and WIDTHS[ord(ch)] else "?" for ch in value)


def width(value):
    return sum(WIDTHS[ord(ch)] if ord(ch) < len(WIDTHS) and WIDTHS[ord(ch)] else WIDTHS[ord("?")]
               for ch in value)


def fit_name(value, pixels, lines=2, extension=True):
    """At most ``lines`` lines, each <= ``pixels``; retain a short file extension after the ellipsis."""
    if pixels < width("…") or lines < 1:
        raise ValueError("name slot is too small")
    name = clean(value)
    rest, result = name, []
    for _ in range(lines - 1):
        if width(rest) <= pixels:
            break
        count, used = 0, 0
        for ch in rest:
            size = width(ch)
            if used + size > pixels:
                break
            count, used = count + 1, used + size
        if count == 0:
            break
        # Prefer a word boundary, without turning a nearly full line into a very short one.
        for split in range(count, max(0, int(count * 0.4)), -1):
            if rest[split - 1] in "_- " or (split < len(rest) and rest[split] == "."):
                count = split
                break
        result.append(rest[:count].rstrip(" "))         # a space at the end of a line would push the centred line to one side
        rest = rest[count:].lstrip(" ")
    if width(rest) > pixels:
        dot = name.rfind(".")
        ext = name[dot:] if extension and dot > 0 and len(name) - dot <= 9 else ""
        if not rest.endswith(ext) or width("…" + ext) > pixels:
            ext = ""
        stem = rest[:-len(ext)] if ext else rest
        while stem and width(stem + "…" + ext) > pixels:
            stem = stem[:-1]
        rest = stem + "…" + ext
    result.append(rest)
    return "\\r".join(result)


def _hard_split(word, pixels):
    """A word wider than a line: cut into pieces that fit."""
    pieces, piece, used = [], "", 0
    for ch in word:
        size = width(ch)
        if used + size > pixels and piece:
            pieces.append(piece)
            piece, used = "", 0
        piece, used = piece + ch, used + size
    return pieces + [piece]


def wrap_text(value, pixels, lines):
    """A message of the host in the lines of a text box: wrapped at the spaces (a word is never cut, unless it is wider than the line),
    a new line of the message stays one, and what does not fit into ``lines`` ends with an ellipsis.  The lines are joined with ``\\r`` (the screen's line break)."""
    result = []
    for paragraph in str(value).replace("\r", "\n").split("\n"):
        current = ""
        for word in clean(paragraph).split():
            for piece in (_hard_split(word, pixels) if width(word) > pixels else [word]):
                candidate = piece if not current else current + " " + piece
                if width(candidate) <= pixels:
                    current = candidate
                else:
                    result.append(current)
                    current = piece
        if current or not result:
            result.append(current)
    result = [line for line in result if line] or [""]
    if len(result) > lines:
        last = result[lines - 1]
        while last and width(last + "…") > pixels:
            last = last[:-1]
        result = result[:lines - 1] + [last.rstrip() + "…"]
    return "\\r".join(result)
